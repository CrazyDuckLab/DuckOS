// TestControllerLastOutcome confirms the last outcome
// is preserved across calls so the operator can see
// the result of the most recent Apply.
func TestControllerLastOutcome(t *testing.T) {
	runner := &fakeRunner{}
	c, _ := NewController(runner)
	p := samplePlan(t)
	out, err := c.Apply(context.Background(), p)
	if err != nil {
		t.Fatalf("apply: %v", err)
	}
	if out.Applied != len(p.Steps) {
		t.Fatalf("expected outcome applied=%d, got %d", len(p.Steps), out.Applied)
	}
	if c.Last().Applied != out.Applied {
		t.Fatalf("expected last outcome to mirror apply, got %+v", c.Last())
	}
}

