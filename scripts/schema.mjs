// This intentionally small generator supports only the repository's v1 schema vocabulary.
import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../shared/api/', import.meta.url);
const schema = JSON.parse(await readFile(new URL('overview.schema.json', base), 'utf8'));
function type(s) {
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(JSON.stringify).join(' | ');
  if (Array.isArray(s.type)) return s.type.map(t => type({ ...s, type: t })).join(' | ');
  if (s.type === 'object') return `{ ${Object.entries(s.properties).map(([k, v]) => `${k}${s.required.includes(k) ? '' : '?'}: ${type(v)};`).join(' ')} }`;
  if (s.type === 'array') return `Array<${type(s.items)}>`;
  if (s.type === 'integer' || s.type === 'number') return 'number';
  if (['string', 'null', 'boolean'].includes(s.type)) return s.type;
  throw new Error(`Unsupported schema: ${JSON.stringify(s)}`);
}
const result = `// Generated by node scripts/schema.mjs; edit overview.schema.json instead.\nexport type Family = 'ipv4' | 'ipv6';\nexport type Overview = ${type(schema)};\n`;
const destination = new URL('types.ts', base);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== result) throw new Error('Shared API types have drifted; run node scripts/schema.mjs.');
  console.log('Shared TypeScript/schema contract matches.');
} else await writeFile(destination, result);
