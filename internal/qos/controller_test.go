// controller_test.go exercises the Agent-side
// Controller with a fake Runner. The Linux adapter
// has its own test under tests/integration; this file
// is the unit-level coverage of the contract.
package qos

import (
	"context"
	"errors"
	"sync/atomic"
	"testing"
	"time"
)

// fakeRunner is a deterministic, fake Runner. It
// records the calls the Controller made and reports
// the plan back to the test. Tests pin the behaviour
// through a counter and a fail flag.
type fakeRunner struct {
	apply    int32
	roll     int32
	state    int32
	fail     bool
	rollOnly bool
	planOut  Plan
	stOut    RunnerState
	stErr    error
}

func (f *fakeRunner) Apply(_ context.Context, p Plan) (ApplyOutcome, error) {
	atomic.AddInt32(&f.apply, 1)
	if f.fail {
		return ApplyOutcome{StartedAt: time.Unix(0, 0)}, errors.New("boom")
	}
	f.planOut = p
	return ApplyOutcome{Applied: len(p.Steps), StartedAt: time.Unix(0, 0), EndedAt: time.Unix(0, 1)}, nil
}

func (f *fakeRunner) Rollback(_ context.Context, cur, prev Plan) (ApplyOutcome, error) {
	atomic.AddInt32(&f.roll, 1)
	// rollOnly lets a test exercise the apply-fails-but-
	// rollback-succeeds path; without it Rollback fails
	// too (because fail is shared) so we can exercise the
	// double-failure guarded path.
	if f.fail && !f.rollOnly {
		return ApplyOutcome{}, errors.New("boom")
	}
	f.planOut = prev
	return ApplyOutcome{Applied: len(cur.Steps) + len(prev.Steps)}, nil
}

func (f *fakeRunner) State(_ context.Context) (RunnerState, error) {
	atomic.AddInt32(&f.state, 1)
	return f.stOut, f.stErr
}

// samplePlan returns a small, valid Plan for the
// controller tests. The Plan is generated by Render so
// the controller test never relies on hand-built
// internals.
func samplePlan(t *testing.T) Plan {
	t.Helper()
	sh := Shaper{ID: "wan1", Link: "wan1", Direction: DirectionEgress, Algorithm: AlgorithmCAKE, RateKbps: 1000, BurstKbyte: 32, Priority: PriorityVoice}
	tp, err := Build([]Shaper{sh}, nil, nil, time.Unix(1, 0))
	if err != nil {
		t.Fatalf("build failed: %v", err)
	}
	p, err := Render(tp)
	if err != nil {
		t.Fatalf("render failed: %v", err)
	}
	return p
}

// TestControllerApplyRollsPrevious confirms a
// successful Apply rotates the previous plan into
// Previous and stores the new plan as Current.
func TestControllerApplyRollsPrevious(t *testing.T) {
	runner := &fakeRunner{}
	c, err := NewController(runner)
	if err != nil {
		t.Fatalf("new controller: %v", err)
	}
	p1 := samplePlan(t)
	p1.Steps[0].Comment = "first"
	if _, err := c.Apply(context.Background(), p1); err != nil {
		t.Fatalf("apply p1: %v", err)
	}
	if got := c.Current().Steps; got[0].Comment != "first" {
		t.Fatalf("expected current to be p1, got %+v", got[0].Comment)
	}
	if len(c.Previous().Steps) != 0 {
		t.Fatalf("expected previous to be empty before second apply")
	}
	p2 := samplePlan(t)
	p2.Steps[0].Comment = "second"
	if _, err := c.Apply(context.Background(), p2); err != nil {
		t.Fatalf("apply p2: %v", err)
	}
	if got := c.Current().Steps; got[0].Comment != "second" {
		t.Fatalf("expected current to be p2, got %+v", got[0].Comment)
	}
	if got := c.Previous().Steps; got[0].Comment != "first" {
		t.Fatalf("expected previous to be p1, got %+v", got[0].Comment)
	}
	if atomic.LoadInt32(&runner.apply) != 2 {
		t.Fatalf("expected 2 apply calls, got %d", runner.apply)
	}
}

// TestControllerApplyRejectsInvalid checks the
// Controller refuses a plan that does not validate.
// The Runner must never be called on a bad plan.
func TestControllerApplyRejectsInvalid(t *testing.T) {
	runner := &fakeRunner{}
	c, _ := NewController(runner)
	bad := Plan{SchemaVersion: "0"}
	if _, err := c.Apply(context.Background(), bad); err == nil {
		t.Fatalf("expected bad plan to be rejected")
	}
	if atomic.LoadInt32(&runner.apply) != 0 {
		t.Fatalf("runner must not be called for a bad plan")
	}
}

// TestControllerApplyFailurePreservesPrevious covers
// the "apply failed" path: the previous plan is kept
// so a follow-up Apply with a corrected plan still has
// a sane rollback anchor.
func TestControllerApplyFailurePreservesPrevious(t *testing.T) {
	runner := &fakeRunner{}
	c, _ := NewController(runner)
	p1 := samplePlan(t)
	p1.Steps[0].Comment = "first"
	if _, err := c.Apply(context.Background(), p1); err != nil {
		t.Fatalf("apply p1: %v", err)
	}
	runner.fail = true
	p2 := samplePlan(t)
	p2.Steps[0].Comment = "second"
	if _, err := c.Apply(context.Background(), p2); err == nil {
		t.Fatalf("expected second apply to fail")
	}
	if got := c.Current().Steps; got[0].Comment != "first" {
		t.Fatalf("expected current to remain p1, got %+v", got[0].Comment)
	}
	if len(c.Previous().Steps) != 0 {
		t.Fatalf("expected previous to remain empty, got %d steps", len(c.Previous().Steps))
	}
}

// TestControllerGuardedRollback proves that a failed
// Apply automatically asks the Runner to restore the
// previous plan so a partially applied plan does not
// leave live tc in an indeterminate state. The
// ApplyOutcome MUST carry the structured warning the
// audit requires; Current and Previous MUST remain
// pinned to the pre-apply state.
func TestControllerGuardedRollback(t *testing.T) {
	runner := &fakeRunner{}
	c, _ := NewController(runner)
	p1 := samplePlan(t)
	p1.Steps[0].Comment = "first"
	if _, err := c.Apply(context.Background(), p1); err != nil {
		t.Fatalf("apply p1: %v", err)
	}
	// Apply-only failure: Rollback still succeeds.
	runner.fail = true
	runner.rollOnly = true
	p2 := samplePlan(t)
	p2.Steps[0].Comment = "second"
	out, err := c.Apply(context.Background(), p2)
	if err == nil {
		t.Fatal("expected apply to fail")
	}
	if atomic.LoadInt32(&runner.roll) == 0 {
		t.Fatal("guarded execution did not invoke Runner.Rollback")
	}
	if got := c.Current().Steps; got[0].Comment != "first" {
		t.Fatalf("Current after guarded rollback: %+v, want first", got[0].Comment)
	}
	if len(c.Previous().Steps) != 0 {
		t.Fatalf("Previous after guarded rollback: %d steps, want empty", len(c.Previous().Steps))
	}
	found := false
	for _, w := range out.Warnings {
		if w == "apply reverted via guarded rollback" {
			found = true
			break
		}
	}
	if !found {
		t.Fatalf("ApplyOutcome warnings missing guarded-rollback marker: %v", out.Warnings)
	}
}

// TestControllerGuardedRollbackSurfacesDoubleFailure proves
// that when BOTH Apply and the guarded Rollback fail, the
// ApplyOutcome carries a structured warning that names the
// indeterminate live state so the operator knows manual
// intervention is required.
func TestControllerGuardedRollbackSurfacesDoubleFailure(t *testing.T) {
	runner := &fakeRunner{}
	c, _ := NewController(runner)
	p1 := samplePlan(t)
	p1.Steps[0].Comment = "first"
	if _, err := c.Apply(context.Background(), p1); err != nil {
		t.Fatalf("apply p1: %v", err)
	}
	runner.fail = true
	p2 := samplePlan(t)
	p2.Steps[0].Comment = "second"
	out, err := c.Apply(context.Background(), p2)
	if err == nil {
		t.Fatal("expected apply to fail")
	}
	hasIndeterminate := false
	for _, w := range out.Warnings {
		if w == "live tc surface may be indeterminate; operator intervention required" {
			hasIndeterminate = true
			break
		}
	}
	if !hasIndeterminate {
		t.Fatalf("ApplyOutcome warnings missing indeterminate marker: %v", out.Warnings)
	}
}

// TestControllerRollback confirms Rollback asks the
// Runner to restore the previous plan and rotates the
// states. After a Rollback the previous becomes the
// current and the current becomes the new previous.
func TestControllerRollback(t *testing.T) {
	runner := &fakeRunner{}
	c, _ := NewController(runner)
	p1 := samplePlan(t)
	p1.Steps[0].Comment = "first"
	p2 := samplePlan(t)
	p2.Steps[0].Comment = "second"
	if _, err := c.Apply(context.Background(), p1); err != nil {
		t.Fatalf("apply p1: %v", err)
	}
	if _, err := c.Apply(context.Background(), p2); err != nil {
		t.Fatalf("apply p2: %v", err)
	}
	if _, err := c.Rollback(context.Background()); err != nil {
		t.Fatalf("rollback: %v", err)
	}
	if got := c.Current().Steps; got[0].Comment != "first" {
		t.Fatalf("expected current to revert to p1, got %+v", got[0].Comment)
	}
	if got := c.Previous().Steps; got[0].Comment != "second" {
		t.Fatalf("expected previous to be p2, got %+v", got[0].Comment)
	}
	if atomic.LoadInt32(&runner.roll) != 1 {
		t.Fatalf("expected one rollback call")
	}
}

