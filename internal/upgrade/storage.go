package upgrade

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"os"
	"path/filepath"
	"sort"
	"sync"
	"syscall"
	"time"
)

// ReleaseStore owns the on-disk layout for Active/Previous/Candidate
// releases. The store is the only place that touches the immutable
// directories; callers do not delete or rename releases outside the
// helper methods here. The layout is:
//
//	<release-dir>/<id>/release.json   fingerprint + metadata
//	<release-dir>/<id>/payload        architecture-specific bytes
//	<release-dir>/active               symlink to the active id
//	<release-dir>/previous             symlink to the previous id
//
// "Active" and "Previous" are reserved names that can never be the
// id of a real release; the store refuses to materialise a release
// with those ids.
type ReleaseStore struct {
	mu       sync.Mutex
	dir      string
	maxBytes int64
}

// NewReleaseStore opens the on-disk store at the given directory. A
// missing directory is created with 0700. The maxBytes argument is
// the upper bound on a single release's payload; the bounded value
// defends against a hostile or misconfigured package filling the
// system partition.
func NewReleaseStore(dir string, maxBytes int64) (*ReleaseStore, error) {
	if dir == "" {
		return nil, errors.New("release store requires a directory")
	}
	if maxBytes <= 0 {
		maxBytes = MaxPayloadBytes
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, err
	}
	info, err := os.Lstat(dir)
	if err != nil {
		return nil, err
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !info.IsDir() || !ok || int(owner.Uid) != os.Geteuid() {
		return nil, errors.New("release store must be an owned real directory")
	}
	if err = os.Chmod(dir, 0700); err != nil {
		return nil, err
	}
	return &ReleaseStore{dir: dir, maxBytes: maxBytes}, nil
}

// ReleaseMeta is the metadata stored next to the payload. It is
// generated by the engine after the package is verified; a Candidate
// is never selectable as Active until its meta is present.
type ReleaseMeta struct {
	ID            string `json:"id"`
	Architecture  string `json:"architecture"`
	SourceVersion string `json:"sourceVersion"`
	TargetVersion string `json:"targetVersion"`
	PayloadDigest string `json:"payloadDigest"`
	PayloadBytes  int64  `json:"payloadBytes"`
	InstalledAt   string `json:"installedAt"`
}

// Materialize stages a verified package into a new release directory.
// The function refuses to overwrite an existing release; callers must
// explicitly remove a previous candidate first. The payload is
// written atomically through a temporary file and renamed in place.
func (s *ReleaseStore) Materialize(meta ReleaseMeta, payload []byte) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if !validStoredReleaseID(meta.ID) {
		return errors.New("release id is invalid or reserved")
	}
	if int64(len(payload)) > s.maxBytes {
		return errors.New("payload exceeds the release store size cap")
	}
	dir := filepath.Join(s.dir, meta.ID)
	if _, err := os.Lstat(dir); err == nil {
		return errors.New("release directory already exists; refuse to overwrite")
	}
	if err := os.Mkdir(dir, 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, "payload.tmp.")
	if err != nil {
		return err
	}
	if _, err := tmp.Write(payload); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Rename(tmp.Name(), filepath.Join(dir, "payload")); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	sum := sha256.Sum256(payload)
	meta.PayloadDigest = hex.EncodeToString(sum[:])
	meta.PayloadBytes = int64(len(payload))
	meta.InstalledAt = nowString()
	raw, _ := json.MarshalIndent(meta, "", "  ")
	metaFile, err := os.OpenFile(filepath.Join(dir, "release.json"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	_, err = metaFile.Write(raw)
	if err == nil {
		err = metaFile.Sync()
	}
	closeErr := metaFile.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	if err = syncReleaseDir(dir); err != nil {
		return err
	}
	return syncReleaseDir(s.dir)
}

// Activate atomically replaces the Active symlink. Previous is
// moved to the new Active before the symlink is flipped so the
// rollback set is always one release wide.
func (s *ReleaseStore) Activate(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if !validStoredReleaseID(id) {
		return errors.New("release id is invalid or reserved")
	}
	if err := s.VerifyFingerprint(id); err != nil {
		return err
	}
	active := filepath.Join(s.dir, string(ReleaseActive))
	if target, err := os.Readlink(active); err == nil {
		if !validStoredReleaseID(target) {
			return errors.New("active anchor is invalid")
		}
		if target == id {
			return nil
		}
		if err = s.VerifyFingerprint(target); err != nil {
			return err
		}
		if err = s.replaceAnchor(string(ReleasePrevious), target); err != nil {
			return err
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return s.replaceAnchor(string(ReleaseActive), id)
}

// Deactivate durably clears the first, unverified activation selection. Release
// payloads remain available for diagnosis; no release directory is deleted.
func (s *ReleaseStore) Deactivate() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, name := range []string{string(ReleaseActive), string(ReleasePrevious)} {
		path := filepath.Join(s.dir, name)
		if _, err := os.Readlink(path); errors.Is(err, os.ErrNotExist) {
			continue
		} else if err != nil {
			return err
		}
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return syncReleaseDir(s.dir)
}

// List returns every materialised release in stable order.
func (s *ReleaseStore) List() ([]string, error) {
	entries, err := os.ReadDir(s.dir)
	if err != nil {
		return nil, err
	}
	out := []string{}
	for _, e := range entries {
		name := e.Name()
		if name == string(ReleaseActive) || name == string(ReleasePrevious) {
			continue
		}
		if e.IsDir() {
			out = append(out, name)
		}
	}
	sort.Strings(out)
	return out, nil
}

// ReadMeta loads the metadata for a release. A missing release is an
// explicit refusal.
func (s *ReleaseStore) ReadMeta(id string) (ReleaseMeta, error) {
	if !validStoredReleaseID(id) {
		return ReleaseMeta{}, errors.New("release id is invalid")
	}
	if err := s.checkReleaseFile(id, "release.json", MaxManifestBytes); err != nil {
		return ReleaseMeta{}, err
	}
	raw, err := os.ReadFile(filepath.Join(s.dir, id, "release.json"))
	if err != nil {
		return ReleaseMeta{}, err
	}
	var meta ReleaseMeta
	if err := json.Unmarshal(raw, &meta); err != nil {
		return ReleaseMeta{}, err
	}
	if meta.ID != id {
		return ReleaseMeta{}, errors.New("release metadata identity mismatch")
	}
	return meta, nil
}

// ReadPayload returns the bytes of a release payload. The bytes are
// caller-owned; the store never holds references to the slice.
func (s *ReleaseStore) ReadPayload(id string) ([]byte, error) {
	if !validStoredReleaseID(id) {
		return nil, errors.New("release id is invalid")
	}
	if err := s.checkReleaseFile(id, "payload", s.maxBytes); err != nil {
		return nil, err
	}
	f, err := os.Open(filepath.Join(s.dir, id, "payload"))
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if info.Size() > s.maxBytes {
		return nil, errors.New("payload exceeds the release store size cap")
	}
	data, err := io.ReadAll(io.LimitReader(f, s.maxBytes+1))
	if int64(len(data)) > s.maxBytes {
		return nil, errors.New("payload exceeds size cap")
	}
	return data, err
}

// Remove deletes a non-active release. Active and Previous are
// reserved; callers must use Activate to swap them. The function
// refuses to delete a release referenced by Active or Previous.
func (s *ReleaseStore) Remove(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if !validStoredReleaseID(id) {
		return errors.New("release id is invalid")
	}
	active, err := os.Readlink(filepath.Join(s.dir, string(ReleaseActive)))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	previous, err := os.Readlink(filepath.Join(s.dir, string(ReleasePrevious)))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if id == active {
		return errors.New("cannot remove the active release")
	}
	if id == previous {
		return errors.New("cannot remove the previous release; promote a new previous first")
	}
	return os.RemoveAll(filepath.Join(s.dir, id))
}

// FreeBytes returns the bytes available to the store, taking the
// store's hard cap into account.
func (s *ReleaseStore) FreeBytes() (int64, error) {
	var st syscall.Statfs_t
	if err := syscall.Statfs(s.dir, &st); err != nil {
		return 0, err
	}
	return int64(st.Bavail) * int64(st.Bsize), nil
}

// VerifyFingerprint is a quick consistency check that compares the
// release.json payload digest with the bytes on disk. The function
// returns nil when the release is intact, an error otherwise.
func (s *ReleaseStore) VerifyFingerprint(id string) error {
	meta, err := s.ReadMeta(id)
	if err != nil {
		return err
	}
	payload, err := s.ReadPayload(id)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(payload)
	if int64(len(payload)) != meta.PayloadBytes || hex.EncodeToString(sum[:]) != meta.PayloadDigest {
		return errors.New("release payload digest mismatch")
	}
	return nil
}

// String returns a non-secret summary of the store.
func (s *ReleaseStore) String() string {
	return "[release store at " + s.dir + "]"
}

// nowString returns the canonical UTC RFC3339Nano string. It is a
// thin wrapper so the storage layer can swap the clock in tests.
var nowString = func() string {
	return time.Now().UTC().Format(time.RFC3339Nano)
}

var _ = filepath.Join
var _ = sort.Strings

func validStoredReleaseID(id string) bool {
	return idPattern.MatchString(id) && id != "." && id != ".." && id != string(ReleaseActive) && id != string(ReleasePrevious)
}
func syncReleaseDir(path string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return f.Sync()
}

// Both anchors are individually replaced atomically. Persist Previous before Active;
// a crash between the two leaves the old Active usable. No unlink-before-create gap.
func (s *ReleaseStore) replaceAnchor(name, target string) error {
	tmp, err := os.MkdirTemp(s.dir, ".anchor-")
	if err != nil {
		return err
	}
	defer os.Remove(tmp)
	link := filepath.Join(tmp, "link")
	defer os.Remove(link)
	if err = os.Symlink(target, link); err != nil {
		return err
	}
	if err = os.Rename(link, filepath.Join(s.dir, name)); err != nil {
		return err
	}
	return syncReleaseDir(s.dir)
}
func (s *ReleaseStore) checkReleaseFile(id, name string, limit int64) error {
	info, err := os.Lstat(filepath.Join(s.dir, id))
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return errors.New("release is not a real directory")
	}
	info, err = os.Lstat(filepath.Join(s.dir, id, name))
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Size() > limit {
		return errors.New("release file is not regular or exceeds size cap")
	}
	return nil
}
