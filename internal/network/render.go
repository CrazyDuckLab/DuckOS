package network

import (
	"errors"
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

// Plan contains only generated artifacts. Keys are basenames under the
// adapter's fixed owned directory, never user-selected filesystem paths.
type Plan struct {
	Networkd map[string]string `json:"networkd"`
	DNSMasq  string            `json:"dnsmasq"`
	NFTables string            `json:"nftables"`
}

var ErrPlanLimit = errors.New("generated configuration exceeds artifact capacity")

func Render(c Config) (Plan, error) {
	if err := c.Validate(); err != nil {
		return Plan{}, err
	}
	p := Plan{Networkd: map[string]string{}}
	if len(c.Interfaces) == 0 {
		// An unenrolled/fully removed configuration must not install packet
		// filtering hooks or start a DNS listener on the existing host.
		// The adapter must prove table ownership before executing this batch.
		p.NFTables = "destroy table inet duckos\n"
		return p, nil
	}
	links := map[string]Interface{}
	for _, i := range c.Interfaces {
		links[i.ID] = i
	}
	ordered := append([]Interface(nil), c.Interfaces...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].ID < ordered[j].ID })
	for _, i := range ordered {
		switch i.Kind {
		case "vlan":
			p.Networkd["10-duckos-"+i.ID+".netdev"] = fmt.Sprintf("[NetDev]\nName=%s\nKind=vlan\nMTUBytes=%d\n\n[VLAN]\nId=%d\n", i.Name, i.MTU, i.VLAN)
		case "bridge":
			ports := []string{}
			for _, child := range ordered {
				if child.Parent == i.ID {
					ports = append(ports, child.Name)
				}
			}
			sort.Strings(ports)
			body := fmt.Sprintf("[NetDev]\nName=%s\nKind=bridge\nMTUBytes=%d\n\n[Bridge]\nSTP=no\n", i.Name, i.MTU)
			for _, p := range ports {
				body += fmt.Sprintf("Bind=%s\n", p)
			}
			p.Networkd["10-duckos-"+i.ID+".netdev"] = body
		}
		var b strings.Builder
		fmt.Fprintf(&b, "[Match]\nName=%s\n\n[Link]\nMTUBytes=%d\nRequiredForOnline=no\n\n[Network]\nDHCP=%s\nIPv6AcceptRA=%s\nLinkLocalAddressing=ipv6\nLLMNR=no\nMulticastDNS=no\n", i.Name, i.MTU, map[string]string{"none": "no", "ipv4": "ipv4", "ipv6": "ipv6", "dual": "yes"}[i.DHCPClient], yesno(i.AcceptRA))
		if i.Role == "lan" {
			b.WriteString("ConfigureWithoutCarrier=yes\n")
		} else {
			// WAN physical interfaces frequently land on a freshly
			// adopted link whose carrier is not yet up (uplink patch
			// panel, idle trunk port, or an AP that's mid-association).
			// Without this directive, networkd keeps the link in
			// AdministrativeState=configuring until the carrier appears,
			// which would block every Safe Apply on the upstream-WAN
			// adoption path. WAN static addresses are still applied
			// without the carrier, which is the desired behaviour.
			b.WriteString("ConfigureWithoutCarrier=yes\n")
		}
		for _, a := range i.Addresses {
			fmt.Fprintf(&b, "Address=%s\n", a)
		}
		for _, v := range ordered {
			if v.Kind == "vlan" && v.Parent == i.ID {
				fmt.Fprintf(&b, "VLAN=%s\n", v.Name)
			}
		}
		b.WriteString("\n[DHCPv4]\nUseDNS=no\nUseHostname=no\n\n[DHCPv6]\nUseDNS=no\nUseHostname=no\n\n[IPv6AcceptRA]\nUseDNS=no\n")
		for _, r := range c.Routes {
			if r.Interface == i.ID {
				fmt.Fprintf(&b, "\n[Route]\nDestination=%s\nMetric=%d\nTable=%d\n", r.Destination, effectiveRouteMetric(r), r.Table)
				if r.Gateway != "" {
					fmt.Fprintf(&b, "Gateway=%s\n", r.Gateway)
					if privateRouteTable(r.Table) {
						b.WriteString("GatewayOnLink=yes\n")
					}
				}
			}
		}
		if i.ID == c.policyAnchor() {
			c.renderPolicy(&b)
		}
		p.Networkd["10-duckos-"+i.ID+".network"] = b.String()
	}
	var dns strings.Builder
	dns.WriteString("# Generated by DuckOS; do not edit.\nport=53\nbind-dynamic\nno-resolv\nno-hosts\ndomain-needed\nbogus-priv\nstop-dns-rebind\ncache-size=1000\ndns-forward-max=150\ndhcp-lease-max=4096\ndhcp-leasefile=/var/lib/duckos-dnsmasq/leases\n")
	lanCount := 0
	for _, i := range ordered {
		if i.Role != "lan" {
			continue
		}
		lanCount++
		fmt.Fprintf(&dns, "interface=%s\n", i.Name)
		if i.DHCPServer == nil {
			fmt.Fprintf(&dns, "no-dhcp-interface=%s\n", i.Name)
			continue
		}
		d := i.DHCPServer
		start, _ := netip.ParseAddr(d.Start)
		var subnet netip.Prefix
		for _, raw := range i.Addresses {
			a, _ := netip.ParsePrefix(raw)
			if a.Contains(start) {
				subnet = a
				break
			}
		}
		mask := uint32(0xffffffff) << (32 - subnet.Bits())
		fmt.Fprintf(&dns, "dhcp-range=set:%s,%s,%s,%d.%d.%d.%d,%ds\ndhcp-option=tag:%s,option:router,%s\ndhcp-option=tag:%s,option:dns-server,%s\n", i.ID, d.Start, d.End, byte(mask>>24), byte(mask>>16), byte(mask>>8), byte(mask), d.LeaseSeconds, i.ID, subnet.Addr(), i.ID, subnet.Addr())
		for _, r := range d.Reservations {
			fmt.Fprintf(&dns, "dhcp-host=%s,%s,%s\n", r.MAC, r.Address, r.Hostname)
		}
	}
	for _, u := range c.DNS.Upstreams {
		fmt.Fprintf(&dns, "server=%s\n", u)
	}
	for _, r := range c.DNS.Records {
		fmt.Fprintf(&dns, "host-record=%s,%s\n", r.Name, r.Address)
	}
	if lanCount > 0 {
		p.DNSMasq = dns.String()
	} else if len(c.DNS.Upstreams) > 0 || len(c.DNS.Records) > 0 {
		return Plan{}, errors.New("DNS service requires a managed LAN listener")
	}
	var nft strings.Builder
	// Destroy/recreate in one batch removes obsolete base chains too. Flushing
	// rules alone can leave their drop policies hooked into the packet path.
	// Only this dedicated table is replaced; unrelated tables remain untouched.
	//
	// DuckOS firewall scope: the policy-drop chain must only filter
	// packets whose incoming interface is one DuckOS owns in this
	// candidate. An externally-managed link (enrollment.Physical with
	// ExternallyManaged=true, e.g. eth0 under dhcpcd) is owned by
	// something else and must not be subject to DuckOS INPUT filtering,
	// because DuckOS has no authority to enumerate its services or
	// distinguish a hostile packet from a legitimate management frame.
	// Without this rule, a Safe Apply that adopts only eth1/eth2 would
	// silently install an INPUT policy-drop that blackholes the host's
	// own management plane on eth0.
	managedNames := make([]string, 0, len(ordered))
	for _, i := range ordered {
		if i.Kind == "physical" || i.Kind == "bridge" || i.Kind == "vlan" {
			managedNames = append(managedNames, i.Name)
		}
	}
	nft.WriteString("destroy table inet duckos\ntable inet duckos {\n chain input {\n  type filter hook input priority filter; policy drop;\n")
	if len(managedNames) > 0 {
		fmt.Fprintf(&nft, "  iifname != { %s } accept\n", joinQuoted(managedNames, ", "))
	} else {
		// No DuckOS-managed links: every packet is on an externally-
		// managed interface, accept unconditionally.
		nft.WriteString("  accept\n")
	}
	nft.WriteString("  iifname \"lo\" accept\n  ct state invalid drop\n  ct state established,related accept\n  meta l4proto ipv6-icmp accept\n  ip protocol icmp accept\n")
	c.renderManagement(&nft, links)
	for _, i := range ordered {
		if i.Management {
			fmt.Fprintf(&nft, "  iifname %q tcp dport { 22, 443 } accept\n", i.Name)
		}
		if i.Role == "lan" {
			fmt.Fprintf(&nft, "  iifname %q udp dport 53 accept\n  iifname %q tcp dport 53 accept\n", i.Name, i.Name)
			if i.DHCPServer != nil {
				fmt.Fprintf(&nft, "  iifname %q udp sport 68 udp dport 67 accept\n", i.Name)
			}
		}
		if i.DHCPClient == "ipv4" || i.DHCPClient == "dual" {
			fmt.Fprintf(&nft, "  iifname %q udp sport 67 udp dport 68 accept\n", i.Name)
		}
		if i.DHCPClient == "ipv6" || i.DHCPClient == "dual" {
			fmt.Fprintf(&nft, "  iifname %q udp sport 547 udp dport 546 accept\n", i.Name)
		}
	}
	compileForward(c).render(&nft, links)
	p.NFTables = nft.String()
	if err := validateArtifacts(p.Networkd); err != nil {
		return Plan{}, fmt.Errorf("%w: %v", ErrPlanLimit, err)
	}
	if len(p.DNSMasq) > 256<<10 || len(p.NFTables) > 512<<10 {
		return Plan{}, ErrPlanLimit
	}
	return p, nil
}
// joinQuoted formats a list of interface names for an nftables set literal.
// Names are emitted as double-quoted strings (nftables accepts both quoted
// and bare words; quoted is safer against names containing dashes or other
// characters that nftables would otherwise tokenize).
func joinQuoted(names []string, sep string) string {
	quoted := make([]string, 0, len(names))
	for _, n := range names {
		quoted = append(quoted, fmt.Sprintf("%q", n))
	}
	return strings.Join(quoted, sep)
}

func yesno(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
