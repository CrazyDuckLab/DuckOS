/**
 * DuckOS V1 — page registry.
 *
 * Source of truth for the 99 V1 pages. Pages not yet wired (no real
 * configurator yet) still register here as `implemented: false` so they
 * render a real page shell — never a fake success — and so the global
 * search and sidebar know where they live.
 *
 * The catalog data comes from docs/ux-v1/page-catalog.json (a design
 * artifact), which we faithfully project into this runtime registry.
 */
import type { SectionId } from "../help/index";

export interface PageMeta {
  /** Stable id from the catalog (P001..P099). */
  id: string;
  /** Display name, in English. Localized via i18n. */
  name: string;
  /** Route — must start with "/". */
  route: string;
  /** Which of the 10 nav sections this page lives under. */
  section: SectionId;
  /** Hero icon name from icons.tsx, where applicable. */
  icon: string;
  /** One-sentence question this page answers, per spec. */
  question: string;
  /** Whether this page has a real configurator wired. */
  implemented: boolean;
  /** Optional feature flag — page is hidden when false. */
  enabled?: boolean;
  /** Comma-separated keywords shown in inspector. */
  features: string;
  /** Comma-separated backend package names. */
  packages: string;
  /** Comma-separated column names for Full-mode table views. */
  columns: string;
  /** Comma-separated filter names. */
  filters: string;
  /** Risk level: R (read), C (change), I (irreversible). */
  risk: "R" | "C" | "I";
  /** Dependencies, joined by semicolon. */
  dependencies: string;
  /** Runtime notes — what could be null/wrong. */
  runtime: string;
  /** Diagnostics entry points. */
  diagnostics: string;
  /** Easy-mode copy shown on the Easy home tile. */
  easyHint: string;
  /** Easy-mode display name shown when Easy mode is active. */
  easyName?: string;
  /** Whether this page is the section landing page (default false). */
  isSectionHome?: boolean;
}

